#include "emit/apple.h"

#include "emit/naming.h"
#include "mc/encoding/json.h"

static void append_components(StringBuilder *out, Rgb rgb)
{
    str_builder_append_format(out, "(%.4f, %.4f, %.4f, %.4f)", rgb.red, rgb.green, rgb.blue, rgb.alpha);
}

static void append_font(Arena *arena, StringBuilder *out, const char *name, String family)
{
    str_builder_append_format(out, "        public static let %s: String? = ", name);
    str_builder_append(out, family.len > 0 ? json_quote(arena, family) : S("nil"));
    str_builder_append_char(out, '\n');
}

static void append_radius(Arena *arena, StringBuilder *out, const char *name, double radius)
{
    String points = emit_length(arena, radius);
    str_builder_append_format(out, "        public static let %s: CGFloat = %.*s\n", name, (int)points.len, points.data);
}

void apple_swift(Arena *arena, const Theme *theme, const EmitOptions *options, Output *output)
{
    String type = naming_type(arena, theme->name);
    bool p3 = options->gamut == GAMUT_DISPLAY_P3;
    StringBuilder out = str_builder_create(arena, 8192);
    str_builder_append_format(&out, "// Generated by tweak from the tweakcn theme \"%.*s\".\n\n", (int)theme->name.len,
                              theme->name.data);
    str_builder_append(&out, S("import SwiftUI\n"
                               "#if canImport(UIKit)\n"
                               "import UIKit\n"
                               "#elseif canImport(AppKit)\n"
                               "import AppKit\n"
                               "#endif\n\n"));
    str_builder_append_format(&out, "public enum %.*s {\n", (int)type.len, type.data);

    str_builder_append(&out, S("    public enum Colors {\n"));
    for (size_t i = 0; i < theme->color_count; i++) {
        const ThemeColor *color = &theme->colors[i];
        String name = naming_camel(arena, color->name);
        str_builder_append_format(&out, "        public static let %.*s = %.*s.color(light: ", (int)name.len, name.data,
                                  (int)type.len, type.data);
        append_components(&out, color_to_rgb(color->light, options->gamut));
        str_builder_append(&out, S(", dark: "));
        append_components(&out, color_to_rgb(color->dark, options->gamut));
        str_builder_append(&out, S(")\n"));
    }
    str_builder_append(&out, S("    }\n"));

    if (theme->has_radius) {
        ThemeRadii radii = theme_radii(theme);
        str_builder_append(&out, S("\n    /// Corner radii in points: shadcn's radius-sm to radius-xl, lg being the theme's radius.\n"
                                   "    public enum Radius {\n"));
        append_radius(arena, &out, "sm", radii.sm);
        append_radius(arena, &out, "md", radii.md);
        append_radius(arena, &out, "lg", radii.lg);
        append_radius(arena, &out, "xl", radii.xl);
        str_builder_append(&out, S("    }\n"));
    }

    str_builder_append(&out, S("\n    /// Font family names for Font.custom(_:size:); nil means the system font.\n"
                               "    /// A custom font must be bundled with the app.\n"
                               "    public enum Fonts {\n"));
    append_font(arena, &out, "sans", theme->font_sans);
    append_font(arena, &out, "serif", theme->font_serif);
    append_font(arena, &out, "mono", theme->font_mono);
    str_builder_append(&out, S("    }\n\n"));

    str_builder_append_format(
        &out,
        "    fileprivate typealias Components = (red: Double, green: Double, blue: Double, alpha: Double)\n\n"
        "    fileprivate static func color(light: Components, dark: Components) -> Color {\n"
        "        #if canImport(UIKit)\n"
        "        Color(uiColor: UIColor { traits in\n"
        "            let c = traits.userInterfaceStyle == .dark ? dark : light\n"
        "            return UIColor(%s: c.red, green: c.green, blue: c.blue, alpha: c.alpha)\n"
        "        })\n"
        "        #elseif canImport(AppKit)\n"
        "        Color(nsColor: NSColor(name: nil) { appearance in\n"
        "            let c = appearance.bestMatch(from: [.aqua, .darkAqua]) == .darkAqua ? dark : light\n"
        "            return NSColor(%s: c.red, green: c.green, blue: c.blue, alpha: c.alpha)\n"
        "        })\n"
        "        #endif\n"
        "    }\n"
        "}\n",
        p3 ? "displayP3Red" : "red", p3 ? "displayP3Red" : "srgbRed");

    output_add(arena, output, str_concat(arena, type, S(".swift")), str_builder_finish(&out));
}

static void append_colorset_color(StringBuilder *out, Rgb rgb, const EmitOptions *options)
{
    str_builder_append_format(out,
                              "      \"color\" : {\n"
                              "        \"color-space\" : \"%s\",\n"
                              "        \"components\" : {\n"
                              "          \"alpha\" : \"%.4f\",\n"
                              "          \"blue\" : \"%.4f\",\n"
                              "          \"green\" : \"%.4f\",\n"
                              "          \"red\" : \"%.4f\"\n"
                              "        }\n"
                              "      },\n"
                              "      \"idiom\" : \"universal\"\n",
                              options->gamut == GAMUT_DISPLAY_P3 ? "display-p3" : "srgb", rgb.alpha, rgb.blue, rgb.green,
                              rgb.red);
}

static String colorset(Arena *arena, const ThemeColor *color, const EmitOptions *options)
{
    StringBuilder out = str_builder_create(arena, 1024);
    str_builder_append(&out, S("{\n  \"colors\" : [\n    {\n"));
    append_colorset_color(&out, color_to_rgb(color->light, options->gamut), options);
    str_builder_append(&out, S("    },\n"
                               "    {\n"
                               "      \"appearances\" : [\n"
                               "        {\n"
                               "          \"appearance\" : \"luminosity\",\n"
                               "          \"value\" : \"dark\"\n"
                               "        }\n"
                               "      ],\n"));
    append_colorset_color(&out, color_to_rgb(color->dark, options->gamut), options);
    str_builder_append(&out, S("    }\n"
                               "  ],\n"
                               "  \"info\" : {\n"
                               "    \"author\" : \"tweak\",\n"
                               "    \"version\" : 1\n"
                               "  }\n"
                               "}\n"));
    return str_builder_finish(&out);
}

void apple_asset_catalog(Arena *arena, const Theme *theme, const EmitOptions *options, Output *output)
{
    String catalog = str_concat(arena, naming_type(arena, theme->name), S(".xcassets"));
    output_add(arena, output, str_concat(arena, catalog, S("/Contents.json")),
               S("{\n  \"info\" : {\n    \"author\" : \"tweak\",\n    \"version\" : 1\n  }\n}\n"));
    for (size_t i = 0; i < theme->color_count; i++) {
        String name = naming_camel(arena, theme->colors[i].name);
        String path = str_format(arena, "%.*s/%.*s.colorset/Contents.json", (int)catalog.len, catalog.data,
                                 (int)name.len, name.data);
        output_add(arena, output, path, colorset(arena, &theme->colors[i], options));
    }
}
