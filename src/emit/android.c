static void append_kotlin_color(StringBuilder *out, Color color, Gamut gamut)
{
    Rgb rgb = color_to_rgb(color, gamut);
    if (gamut == GAMUT_DISPLAY_P3) {
        str_builder_append_format(out, "Color(%.4ff, %.4ff, %.4ff, %.4ff, ColorSpaces.DisplayP3)", rgb.red, rgb.green,
                                  rgb.blue, rgb.alpha);
    } else {
        str_builder_append_format(out, "Color(0x%08X)", rgb_argb(rgb));
    }
}

static void append_palette(Arena *arena, StringBuilder *out, const Theme *theme, String base, bool dark, Gamut gamut)
{
    str_builder_append_format(out, "val %.*s%sColors = %.*sColors(\n", (int)base.len, base.data, dark ? "Dark" : "Light",
                              (int)base.len, base.data);
    for (size_t i = 0; i < theme->color_count; i++) {
        const ThemeColor *color = &theme->colors[i];
        String name = naming_camel(arena, color->name);
        str_builder_append_format(out, "    %.*s = ", (int)name.len, name.data);
        append_kotlin_color(out, dark ? color->dark : color->light, gamut);
        str_builder_append(out, S(",\n"));
    }
    str_builder_append(out, S(")\n\n"));
}

static void append_dp(Arena *arena, StringBuilder *out, const char *format, double value)
{
    String dp = emit_length(arena, value);
    str_builder_append_format(out, format, (int)dp.len, dp.data);
}

static void append_font(Arena *arena, StringBuilder *out, const char *name, String family)
{
    str_builder_append_format(out, "    val %s: String? = ", name);
    str_builder_append(out, family.len > 0 ? json_quote(arena, family) : S("null"));
    str_builder_append_char(out, '\n');
}

void android_compose(Arena *arena, const Theme *theme, const EmitOptions *options, Output *output)
{
    String type = naming_type(arena, theme->name);
    String base = str_trim_suffix(type, S("Theme"));
    String colors_type = str_concat(arena, base, S("Colors"));
    StringBuilder out = str_builder_create(arena, 16384);
    str_builder_append_format(&out, "// Generated by tweak from the tweakcn theme \"%.*s\".\n\n", (int)theme->name.len,
                              theme->name.data);
    if (options->package.len > 0) {
        str_builder_append_format(&out, "package %.*s\n\n", (int)options->package.len, options->package.data);
    }
    str_builder_append(&out, S("import androidx.compose.foundation.isSystemInDarkTheme\n"
                               "import androidx.compose.foundation.shape.RoundedCornerShape\n"
                               "import androidx.compose.material3.ColorScheme\n"
                               "import androidx.compose.material3.MaterialTheme\n"
                               "import androidx.compose.material3.Shapes\n"
                               "import androidx.compose.material3.darkColorScheme\n"
                               "import androidx.compose.material3.lightColorScheme\n"
                               "import androidx.compose.runtime.Composable\n"
                               "import androidx.compose.runtime.CompositionLocalProvider\n"
                               "import androidx.compose.runtime.Immutable\n"
                               "import androidx.compose.runtime.ReadOnlyComposable\n"
                               "import androidx.compose.runtime.staticCompositionLocalOf\n"
                               "import androidx.compose.ui.graphics.Color\n"));
    if (options->gamut == GAMUT_DISPLAY_P3) {
        str_builder_append(&out, S("import androidx.compose.ui.graphics.colorspace.ColorSpaces\n"));
    }
    str_builder_append(&out, S("import androidx.compose.ui.unit.dp\n\n"));

    str_builder_append_format(&out, "@Immutable\ndata class %.*s(\n", (int)colors_type.len, colors_type.data);
    for (size_t i = 0; i < theme->color_count; i++) {
        String name = naming_camel(arena, theme->colors[i].name);
        str_builder_append_format(&out, "    val %.*s: Color,\n", (int)name.len, name.data);
    }
    str_builder_append(&out, S(")\n\n"));
    append_palette(arena, &out, theme, base, false, options->gamut);
    append_palette(arena, &out, theme, base, true, options->gamut);

    str_builder_append_format(&out, "private val Local%.*s = staticCompositionLocalOf { %.*sLightColors }\n\n",
                              (int)colors_type.len, colors_type.data, (int)base.len, base.data);

    str_builder_append_format(&out, "object %.*s {\n", (int)type.len, type.data);
    str_builder_append_format(&out,
                              "    val colors: %.*s\n"
                              "        @Composable @ReadOnlyComposable get() = Local%.*s.current\n\n",
                              (int)colors_type.len, colors_type.data, (int)colors_type.len, colors_type.data);
    if (theme->has_radius) {
        ThemeRadii radii = theme_radii(theme);
        str_builder_append(&out, S("    // shadcn's radius-sm to radius-xl, lg being the theme's radius.\n"));
        append_dp(arena, &out, "    val radiusSm = %.*s.dp\n", radii.sm);
        append_dp(arena, &out, "    val radiusMd = %.*s.dp\n", radii.md);
        append_dp(arena, &out, "    val radiusLg = %.*s.dp\n", radii.lg);
        append_dp(arena, &out, "    val radiusXl = %.*s.dp\n\n", radii.xl);
        str_builder_append(&out, S("    val shapes = Shapes(\n"
                                   "        extraSmall = RoundedCornerShape(radiusSm),\n"
                                   "        small = RoundedCornerShape(radiusMd),\n"
                                   "        medium = RoundedCornerShape(radiusLg),\n"
                                   "        large = RoundedCornerShape(radiusXl),\n"
                                   "        extraLarge = RoundedCornerShape(radiusXl),\n"
                                   "    )\n\n"));
    }
    str_builder_append(&out, S("    // Font family names; null means the system font. Load them with\n"
                               "    // downloadable fonts or bundle them as font resources.\n"));
    append_font(arena, &out, "fontSans", theme->font_sans);
    append_font(arena, &out, "fontSerif", theme->font_serif);
    append_font(arena, &out, "fontMono", theme->font_mono);
    str_builder_append(&out, S("}\n\n"));

    str_builder_append_format(&out,
                              "fun %.*s.toColorScheme(dark: Boolean): ColorScheme =\n"
                              "    (if (dark) darkColorScheme() else lightColorScheme()).copy(\n",
                              (int)colors_type.len, colors_type.data);
    for (size_t i = 0; i < MATERIAL_ROLE_COUNT; i++) {
        const MaterialRole *role = &MATERIAL_ROLES[i];
        if (theme_color(theme, S(role->token)) == nullptr) {
            continue;
        }
        String token = naming_camel(arena, S(role->token));
        str_builder_append_format(&out, "        %s = %.*s,\n", role->compose, (int)token.len, token.data);
    }
    str_builder_append(&out, S("    )\n\n"));

    str_builder_append_format(&out,
                              "@Composable\n"
                              "fun %.*s(darkTheme: Boolean = isSystemInDarkTheme(), content: @Composable () -> Unit) {\n"
                              "    val colors = if (darkTheme) %.*sDarkColors else %.*sLightColors\n"
                              "    CompositionLocalProvider(Local%.*s provides colors) {\n"
                              "        MaterialTheme(\n"
                              "            colorScheme = colors.toColorScheme(darkTheme),\n",
                              (int)type.len, type.data, (int)base.len, base.data, (int)base.len, base.data,
                              (int)colors_type.len, colors_type.data);
    if (theme->has_radius) {
        str_builder_append_format(&out, "            shapes = %.*s.shapes,\n", (int)type.len, type.data);
    }
    str_builder_append(&out, S("            content = content,\n"
                               "        )\n"
                               "    }\n"
                               "}\n"));

    output_add(arena, output, str_concat(arena, type, S(".kt")), str_builder_finish(&out));
}

static String resources(Arena *arena, const Theme *theme, bool dark)
{
    StringBuilder out = str_builder_create(arena, 4096);
    str_builder_append(&out, S("<?xml version=\"1.0\" encoding=\"utf-8\"?>\n"
                               "<!-- Generated by tweak from a tweakcn theme. -->\n"
                               "<resources>\n"));
    for (size_t i = 0; i < theme->color_count; i++) {
        const ThemeColor *color = &theme->colors[i];
        String name = naming_snake(arena, color->name);
        Rgb rgb = color_to_rgb(dark ? color->dark : color->light, GAMUT_SRGB);
        str_builder_append_format(&out, "    <color name=\"%.*s\">#%08X</color>\n", (int)name.len, name.data, rgb_argb(rgb));
    }
    if (!dark && theme->has_radius) {
        ThemeRadii radii = theme_radii(theme);
        append_dp(arena, &out, "    <dimen name=\"radius_sm\">%.*sdp</dimen>\n", radii.sm);
        append_dp(arena, &out, "    <dimen name=\"radius_md\">%.*sdp</dimen>\n", radii.md);
        append_dp(arena, &out, "    <dimen name=\"radius_lg\">%.*sdp</dimen>\n", radii.lg);
        append_dp(arena, &out, "    <dimen name=\"radius_xl\">%.*sdp</dimen>\n", radii.xl);
    }
    str_builder_append(&out, S("</resources>\n"));
    return str_builder_finish(&out);
}

void android_resources(Arena *arena, const Theme *theme, const EmitOptions *options, Output *output)
{
    String file = str_concat(arena, naming_snake(arena, naming_type(arena, theme->name)), S(".xml"));
    output_add(arena, output, str_concat(arena, S("values/"), file), resources(arena, theme, false));
    output_add(arena, output, str_concat(arena, S("values-night/"), file), resources(arena, theme, true));
}
